"""Independently check retained persistent API pilots and inventory all attempts."""

import json
from datetime import datetime, timezone
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from verify_flower import verify_manifest


def main():
    report = {"schema_version": "0.1.0", "checked_at_utc": datetime.now(timezone.utc).isoformat(),
        "kind": "persistent-api-learning-integration", "verified_runs": [], "unverified_attempts": [],
        "aws_resources_created": False, "confirmatory": False, "test_holdout_evaluated": False,
        "limitations": ["DynamoDB Local and Moto S3 do not establish cloud IAM, durability or latency",
            "Eight authenticated Flower clients run on one Windows host, not Fargate",
            "Separate mTLS evaluator process shares host filesystem identity; mount isolation remains open",
            "Retained local audit anchors are not an external hardened witness",
            "One seed and small validation-only engineering samples; no H1-H4 result"]}
    for path in sorted((ROOT / "results/runtime").glob("*/run_manifest.json")):
        config_path = path.parent / "active.json"
        if not config_path.is_file():
            continue
        config = json.loads(config_path.read_text(encoding="utf-8"))
        if config.get("authority_backend") != "dynamodb-s3-opa":
            continue
        try:
            run = verify_manifest(path)
            run.pop("retained_last_launch_config", None)
            services_manifest = None
            for case in json.loads(path.read_text(encoding="utf-8"))["cases"]:
                result = json.loads((ROOT / case["result_file"]).read_text(encoding="utf-8"))
                service_path = Path(result["integration_services"]["services_manifest"])
                services = json.loads(service_path.read_text(encoding="utf-8"))
                actors = json.loads((service_path.parent / "actors.json").read_text(encoding="utf-8"))
                if (services.get("stopped") is not True or actors.get("all_processes_stopped") is not True
                        or run.get("all_launch_listeners_stopped") is not True or run.get("aws_credentials_forwarded") is not False):
                    raise ValueError("integration_cleanup_or_credential_evidence_missing")
                if services_manifest is not None and services_manifest != service_path:
                    raise ValueError("integration_service_binding_changed_within_launch")
                services_manifest = service_path
            run["service_images"] = services["images"]
            run["all_owned_services_stopped"] = True
            report["verified_runs"].append(run)
        except (ValueError, KeyError, OSError) as error:
            report["unverified_attempts"].append({"run_id": path.parent.name,
                "manifest_file": path.relative_to(ROOT).as_posix(), "reason": str(error).split("\n")[0][:200]})
    report["successful"] = bool(report["verified_runs"])
    report["cases_verified"] = sum(len(run["cases"]) for run in report["verified_runs"])
    destination = ROOT / "reports/integration_validation.json"
    destination.write_text(json.dumps(report, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    lines = ["# Persistent API integration validation", "",
        "Generated by `scripts/verify_integrated.py` from retained model, policy, transaction and evaluator evidence.", "",
        "| Launch | Scenario | Models | Accepted | Oracle-invalid presented | Invalid included |",
        "|---|---|---:|---:|---:|---:|"]
    for run in report["verified_runs"]:
        for case in run["cases"]:
            lines.append(f"| {run['run_id']} | {case['scenario_id']} | {case['published_models']} | {case['accepted_updates']} | {case['oracle_invalid_presented']} | {case['oracle_invalid_incorporations']} |")
    lines += ["", f"Verified cases: {report['cases_verified']}. Unverified attempts retained: {len(report['unverified_attempts'])}.", "",
        "The independent verifier checks exact retained S3 versions and hashes, reconstructs FedAvg, evaluates the continuous policy interval, recomputes the candidate fingerprint, checks durable transaction/audit/pointer bindings and verifies the evaluator response against committed model and trusted validation metadata.", ""]
    for attempt in report["unverified_attempts"]:
        lines.append(f"- Unverified `{attempt['run_id']}`: {attempt['reason']}")
    lines += ["", *["- " + limitation for limitation in report["limitations"]], ""]
    (ROOT / "reports/integration_validation.md").write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"verified_runs": len(report["verified_runs"]), "verified_cases": report["cases_verified"],
                      "unverified_attempts": len(report["unverified_attempts"])}, indent=2))
    return 0 if report["successful"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
